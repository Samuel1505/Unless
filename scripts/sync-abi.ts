/**
 * Generates src/app-config/retainer-abi.generated.ts from the compiled artifact of the
 * deployed source (contracts/out/UnlessRetainer.sol/UnlessRetainer.json). The ABI is never
 * hand-written.
 *
 *   bun run sync:abi          write the file
 *   bun run sync:abi --check  exit 1 if the file differs from the artifact
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const artifactPath = resolve(root, 'contracts/out/UnlessRetainer.sol/UnlessRetainer.json')
const outPath = resolve(root, 'src/app-config/retainer-abi.generated.ts')
const checkOnly = process.argv.includes('--check')

if (!existsSync(artifactPath)) {
  console.error(`sync-abi: artifact not found at ${artifactPath}. Run "forge build" first.`)
  process.exit(1)
}

const artifact = JSON.parse(readFileSync(artifactPath, 'utf8')) as { abi: unknown[] }
const body = `// GENERATED by scripts/sync-abi.ts from contracts/out/UnlessRetainer.sol/UnlessRetainer.json.
// Do not edit by hand: run "bun run sync:abi" after a contract rebuild.

export const retainerAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`

if (checkOnly) {
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : ''
  if (current !== body) {
    console.error('sync-abi: src/app-config/retainer-abi.generated.ts is out of date. Run "bun run sync:abi".')
    process.exit(1)
  }
  console.log('sync-abi: generated ABI matches the compiled artifact.')
} else {
  writeFileSync(outPath, body)
  console.log(`sync-abi: wrote ${outPath} (${artifact.abi.length} ABI entries).`)
}
